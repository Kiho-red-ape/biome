import { NextRequest, NextResponse } from 'next/server';
import { createServiceClient } from '@/lib/supabase/server';

export async function GET(req: NextRequest) {
  const id = req.nextUrl.searchParams.get('id');
  if (!id) return NextResponse.json({ error: 'Missing id' }, { status: 400 });

  const db = createServiceClient();

  const [
    { data: exp },
    { data: applications },
    { data: milestones },
    { data: kits },
  ] = await Promise.all([
    db.from('experiments').select('*').eq('id', id).single(),
    db.from('applications').select('*').eq('experiment_id', id),
    db.from('participant_milestones').select('*').eq('experiment_id', id),
    db.from('sample_kits').select('*').eq('experiment_id', id),
  ]);

  if (!exp) return NextResponse.json({ error: 'Study not found' }, { status: 404 });

  const apps          = applications ?? [];
  const ms            = milestones   ?? [];
  const kitList       = kits         ?? [];

  const totalSlots    = (exp.slots_total as number) ?? 0;
  const enrolled      = apps.filter((a) => ['approved', 'completed'].includes(a.status as string)).length;
  const completed     = apps.filter((a) => a.status === 'completed').length;
  const withdrawn     = apps.filter((a) => a.status === 'withdrawn').length;
  const dropoutRate   = enrolled > 0 ? ((withdrawn / enrolled) * 100).toFixed(1) : '0';

  const completedMs   = ms.filter((m) => m.status === 'completed').length;
  const totalMs       = ms.filter((m) => m.status !== 'missed').length;
  const complianceRate = totalMs > 0 ? ((completedMs / totalMs) * 100).toFixed(1) : '—';

  const kitsShipped   = kitList.filter((k) => k.ship_status !== 'pending').length;
  const kitsAtLab     = kitList.filter((k) => ['received_at_lab', 'processing', 'results_ready'].includes(k.return_status as string)).length;
  const kitsReady     = kitList.filter((k) => k.return_status === 'results_ready').length;

  const pendingPayout = apps.filter((a) => a.payout_status === 'pending').length;
  const paidPayout    = apps.filter((a) => a.payout_status === 'paid').length;
  const totalDistributed = apps
    .filter((a) => a.payout_status === 'paid')
    .reduce((sum, a) => sum + ((a.payout_net_amount as number) ?? 0), 0);

  const flags = apps.filter((a) => a.violation_flagged).length;

  const reportDate = new Date().toISOString().slice(0, 10);

  const report = `# BIOME Sponsor Report
## ${exp.title as string}
**Study code:** ${(exp.experiment_code as string | null) ?? id.slice(0, 8)}
**Status:** ${exp.status as string}
**Report date:** ${reportDate}
**Generated by:** Biome Operations

---

## Enrollment

| Metric | Value |
|--------|-------|
| Target participants | ${totalSlots} |
| Currently enrolled | ${enrolled} |
| Completed | ${completed} |
| Withdrawn / dropped | ${withdrawn} |
| Drop-out rate | ${dropoutRate}% |

---

## Compliance

| Metric | Value |
|--------|-------|
| Milestones completed | ${completedMs} / ${totalMs} |
| Compliance rate | ${complianceRate}% |
| Participants flagged | ${flags} |

---

## Sample Logistics

| Stage | Count |
|-------|-------|
| Total kits | ${kitList.length} |
| Shipped to participants | ${kitsShipped} |
| Received at lab | ${kitsAtLab} |
| Results ready | ${kitsReady} |

---

## Payouts

| Metric | Value |
|--------|-------|
| Payouts pending | ${pendingPayout} |
| Payouts completed | ${paidPayout} |
| Total distributed | $${totalDistributed.toFixed(2)} |

---

## Risks & Flags

${flags > 0 ? `- ⚠ ${flags} participant(s) flagged for compliance violations — review in operator console` : '- No compliance flags at this time'}
${(Number(dropoutRate) > 20) ? `- ⚠ Dropout rate (${dropoutRate}%) exceeds 20% — recommend reviewing protocol friction` : ''}

---

*This report was generated automatically from Biome operational data. For questions, contact kishore@biome.to.*
`;

  return NextResponse.json({ report });
}
